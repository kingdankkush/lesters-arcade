import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildDeviceInputQaMatrix } from '../apps/portal/src/device-model.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function renderDeviceInputQaMarkdown(matrix = buildDeviceInputQaMatrix()) {
  const rows = matrix.rows.map((row) => [
    row.id,
    row.pass ? 'PASS' : 'FAIL',
    row.actualClass,
    row.orientation,
    row.touchControls,
    row.landscapeHint,
    row.minTapTargetPx,
    row.inputs.join('; '),
  ]);
  return `# Hard Money Heroes Device and Input QA Matrix\n\nGenerated by \`scripts/hmh-device-input-qa.mjs\`.\n\n## Summary\n\n- Version: ${matrix.version}\n- Status: ${matrix.summary.status}\n- Cases: ${matrix.summary.caseCount}\n- Touch-control cases: ${matrix.summary.touchCaseCount}\n\n${table(['Case', 'Status', 'Device class', 'Orientation', 'Touch controls', 'Landscape hint', 'Min tap target', 'Inputs'], rows)}\n`;
}

export function writeDeviceInputQaMatrix({ repoRoot = repoRootFromHere() } = {}) {
  const matrix = buildDeviceInputQaMatrix();
  const outputDir = path.join(repoRoot, 'docs', 'qa');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'hard-money-heroes-device-input-qa.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-device-input-qa.md');
  writeFileSync(jsonPath, `${JSON.stringify(matrix, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderDeviceInputQaMarkdown(matrix), 'utf8');
  return Object.freeze({ matrix, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { matrix, jsonPath, mdPath } = writeDeviceInputQaMatrix();
  console.log(`HMH device/input QA report written: ${jsonPath}`);
  console.log(`HMH device/input QA markdown written: ${mdPath}`);
  console.log(`Status: ${matrix.summary.status}; cases ${matrix.summary.caseCount}; touch cases ${matrix.summary.touchCaseCount}`);
  if (matrix.summary.status !== 'PASS') process.exitCode = 1;
}
