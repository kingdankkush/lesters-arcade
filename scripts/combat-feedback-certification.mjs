import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildCombatFeedbackScorecard, validateCombatFeedbackCompleteness } from '../apps/portal/src/hmh-combat-feedback.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function renderCombatFeedbackCertificationMarkdown(scorecard, validation) {
  const rows = scorecard.rows.map((row) => [row.id, row.title, row.channels.join(', '), row.missing.length ? row.missing.join(', ') : 'none']);
  return `# Hard Money Heroes Combat Feedback Certification\n\nGenerated by \`scripts/combat-feedback-certification.mjs\`.\n\n## Summary\n\n- Version: ${scorecard.version}\n- Moments covered: ${scorecard.totalMoments}\n- Required channels covered: ${scorecard.totalRequiredChannels - scorecard.totalMissingChannels}/${scorecard.totalRequiredChannels}\n- Score: ${scorecard.overallScore}/100\n- Status: ${validation.ok ? 'PASS' : 'FAIL'}\n\n## Moment scorecard\n\n${table(['Moment', 'Title', 'Channels', 'Missing'], rows)}\n\n## Gaps\n\n${validation.gaps.length ? validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeCombatFeedbackCertification({ repoRoot = repoRootFromHere() } = {}) {
  const scorecard = buildCombatFeedbackScorecard();
  const validation = validateCombatFeedbackCompleteness(scorecard);
  const outputDir = path.join(repoRoot, 'docs', 'art');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'COMBAT_FEEDBACK_CERTIFICATION.json');
  const mdPath = path.join(outputDir, 'COMBAT_FEEDBACK_CERTIFICATION.md');
  writeFileSync(jsonPath, `${JSON.stringify({ scorecard, validation }, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderCombatFeedbackCertificationMarkdown(scorecard, validation), 'utf8');
  return Object.freeze({ scorecard, validation, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { scorecard, validation, jsonPath, mdPath } = writeCombatFeedbackCertification();
  console.log(`Combat feedback certification written: ${jsonPath}`);
  console.log(`Combat feedback markdown written: ${mdPath}`);
  console.log(`Status: ${validation.ok ? 'PASS' : 'FAIL'}; score ${scorecard.overallScore}/100; moments ${scorecard.totalMoments}`);
  if (!validation.ok) process.exitCode = 1;
}
