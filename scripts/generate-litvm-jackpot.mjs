export const JACKPOT_MODULE_BANNER = '// GENERATED by scripts/generate-litvm-jackpot.mjs — do not edit.';
export const JACKPOT_RECORD_SCHEMA_VERSION = 1;
export const JACKPOT_CHAIN_ID = 4441;
export const JACKPOT_GAMES = Object.freeze(['chikun']);
export const CHIKUN_SEASON = 'chikun-season-preview-1';
