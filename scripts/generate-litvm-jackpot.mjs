// Deployment record (contracts/deployment-record.jackpot.json)
// ---------------------------------------------------------------------------------------------------------

function lowerAddress(value, label, { nullable = false } = {}) {
  if (nullable && (value === null || value === undefined || value === ethers.ZeroAddress)) return null;
  if (typeof value !== 'string' || !ADDRESS_RE.test(value)) fail(`${label} must be a 0x address`);
  if (/^0x0{40}$/.test(value)) fail(`${label} must not be the zero address`);
  return value.toLowerCase();
}

function safeInt(value, label, { min = 0 } = {}) {
  const number = typeof value === 'bigint' ? Number(value) : value;
  if (!Number.isSafeInteger(number) || number < min) fail(`${label} must be an integer >= ${min}`);
  return number;
}

function text(value, label) {
  if (typeof value !== 'string' || !TEXT_RE.test(value)) fail(`${label} must be 1-64 printable ASCII characters`);
  return value;
}

export function normalizeTokenInfo(token, label = 'token') {
  if (!token || typeof token !== 'object') fail(`${label} is required`);
  const decimals = safeInt(token.decimals, `${label}.decimals`);
  if (decimals > 36) fail(`${label}.decimals is out of range`);
  if (typeof token.testnet !== 'boolean') fail(`${label}.testnet must be true or false`);
  const deployTx = token.deployTx ?? null;
  if (deployTx !== null && (typeof deployTx !== 'string' || !TX_HASH_RE.test(deployTx))) fail(`${label}.deployTx must be a transaction hash or null`);
  return {
    address: lowerAddress(token.address, `${label}.address`),
    name: text(token.name, `${label}.name`),
    symbol: text(token.symbol, `${label}.symbol`),
    decimals,
    testnet: token.testnet,
    deployTx: deployTx === null ? null : deployTx.toLowerCase(),
  };
}

function normalizeRetired(entry, index) {
  const label = `retired[${index}]`;
  if (!entry || typeof entry !== 'object') fail(`${label} must be an object`);
  return {
    address: lowerAddress(entry.address, `${label}.address`),
    token: normalizeTokenInfo(entry.token, `${label}.token`),
    startBlock: safeInt(entry.startBlock, `${label}.startBlock`),
    firstWeek: safeInt(entry.firstWeek, `${label}.firstWeek`, { min: 1 }),
    endAfterWeek: safeInt(entry.endAfterWeek, `${label}.endAfterWeek`, { min: 1 }),
  };
}

function normalizeInstance(instance, game) {
  const label = `instances.${game}`;
  if (!instance || typeof instance !== 'object') fail(`${label} is required`);
  const firstWeek = safeInt(instance.firstWeek, `${label}.firstWeek`, { min: 1 });
  if (typeof instance.deployTx !== 'string' || !TX_HASH_RE.test(instance.deployTx)) fail(`${label}.deployTx must be a transaction hash`);
  if (typeof instance.gameId !== 'string' || !BYTES32_RE.test(instance.gameId)) fail(`${label}.gameId must be a bytes32`);
  const retired = Array.isArray(instance.retired) ? instance.retired.map(normalizeRetired) : fail(`${label}.retired must be an array`);
  const rules = rulesToJson(instance.rules ?? fail(`${label}.rules is required`));
  if (rules.fromWeek !== firstWeek) fail(`${label}.rules.fromWeek must equal firstWeek`);
  const normalized = {
    game,
    gameId: instance.gameId.toLowerCase(),
    address: lowerAddress(instance.address, `${label}.address`),
    token: normalizeTokenInfo(instance.token, `${label}.token`),
    startBlock: safeInt(instance.startBlock, `${label}.startBlock`),
    deployTx: instance.deployTx.toLowerCase(),
    firstWeek,
    firstWeekKey: weekKeyOf(firstWeek),
    operator: lowerAddress(instance.operator, `${label}.operator`),
    admin: lowerAddress(instance.admin, `${label}.admin`),
    keeper: lowerAddress(instance.keeper, `${label}.keeper`, { nullable: true }),
    residualRecipient: lowerAddress(instance.residualRecipient, `${label}.residualRecipient`),
    scoreRegistry: lowerAddress(instance.scoreRegistry, `${label}.scoreRegistry`),
    rankedEntry: lowerAddress(instance.rankedEntry, `${label}.rankedEntry`),
    rules,
    retired,
  };
  const addresses = [normalized.address, ...retired.map((entry) => entry.address)];
  if (new Set(addresses).size !== addresses.length) fail(`${label}: the active and retired instances must be distinct contracts`);
  for (const entry of retired) {
    if (normalized.firstWeek <= entry.endAfterWeek) fail(`${label}: firstWeek ${normalized.firstWeek} must be after retired ${entry.address} endAfterWeek ${entry.endAfterWeek}`);
  }
  return normalized;
}

// Validates a record and returns its canonical form (lowercase, fixed key order).
export function normalizeJackpotRecord(record) {
  if (!record || typeof record !== 'object') fail('record is required');
  if (record.schemaVersion !== JACKPOT_RECORD_SCHEMA_VERSION) fail(`record.schemaVersion must be ${JACKPOT_RECORD_SCHEMA_VERSION}`);
  if (record.chainId !== JACKPOT_CHAIN_ID) fail(`record.chainId must be ${JACKPOT_CHAIN_ID}`);
  if (typeof record.deployedAt !== 'string' || !ISO_RE.test(record.deployedAt)) fail('record.deployedAt must be an ISO-8601 UTC timestamp');
  const games = Object.keys(record.instances ?? {});
  if (games.join(',') !== JACKPOT_GAMES.join(',')) fail(`record.instances must have exactly ${JACKPOT_GAMES.join(', ')}`);
  return {
    schemaVersion: JACKPOT_RECORD_SCHEMA_VERSION,
    chainId: JACKPOT_CHAIN_ID,
    network: typeof record.network === 'string' ? record.network : 'LitVM LiteForge',
    deployedAt: record.deployedAt,
    instances: Object.fromEntries(JACKPOT_GAMES.map((game) => [game, normalizeInstance(record.instances[game], game)])),
  };
}

// The retired[] entry for an instance that has a scheduled end (endAfterWeek read from chain).
export function retiredEntryOf(instance, endAfterWeek) {
  return normalizeRetired({ address: instance.address, token: instance.token, startBlock: instance.startBlock, firstWeek: instance.firstWeek, endAfterWeek: Number(endAfterWeek) }, 0);
}

// Builds a record for a fresh instance. `previous` (a record) + `previousEndAfterWeek` moves the previous
// active instance into retired[] (after its own retired entries).
export function buildJackpotRecord({ instance, previous = null, previousEndAfterWeek = null, deployedAt = new Date().toISOString(), network = 'LitVM LiteForge' }) {
  const retired = [];
  if (previous) {
    const prior = normalizeJackpotRecord(previous).instances.chikun;
    if (previousEndAfterWeek === null || previousEndAfterWeek === undefined || Number(previousEndAfterWeek) === 0) fail('the previous instance has no scheduled end (run schedule-end on it first)');
    retired.push(...prior.retired, retiredEntryOf(prior, previousEndAfterWeek));
  }
  return normalizeJackpotRecord({
    schemaVersion: JACKPOT_RECORD_SCHEMA_VERSION,
    chainId: JACKPOT_CHAIN_ID,
    network,
    deployedAt,
    instances: { chikun: { ...instance, retired } },
  });
}

