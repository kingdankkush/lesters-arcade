let artifactCache = null;
// { abi, bytecode } of a committed artifact in contracts/artifacts (the jackpot tools never compile).
export function loadContractArtifact(name) {
  artifactCache ??= new Map();
  if (!artifactCache.has(name)) {
    const artifact = JSON.parse(readFileSync(join(repoRoot, 'contracts', 'artifacts', `${name}.json`), 'utf8'));
    const object = artifact.evm?.bytecode?.object ?? '';
    artifactCache.set(name, Object.freeze({ abi: artifact.abi, bytecode: object ? `0x${object.replace(/^0x/, '')}` : '0x' }));
  }
  return artifactCache.get(name);
}

// ---------------------------------------------------------------------------------------------------------
// Week math (design §A.2). Identical to WeeklyJackpot.weekOf / weekBounds.
// ---------------------------------------------------------------------------------------------------------

export const WEEK_SECONDS = 7 * 24 * 3600;
export const WEEK_SHIFT_SECONDS = 3 * 24 * 3600;
export const SETTLE_GRACE_SECONDS = 6 * 3600;
export const CANDIDATE_WINDOW_SECONDS = 12 * 3600;
export const PAYOUT_DELAY_SECONDS = 24 * 3600;
export const RELIST_MARGIN_SECONDS = 2 * 3600;
export const MAX_EXTENSION_SECONDS = 72 * 3600;
export const MAX_FUND_AHEAD_WEEKS = 8;
export const UNCLAIMED_AFTER_SECONDS = 180 * 24 * 3600;
export const RESIDUAL_DELAY_SECONDS = 30 * 24 * 3600;

function toSeconds(value) {
  const number = typeof value === 'bigint' ? Number(value) : Number(value);
  if (!Number.isFinite(number) || number < 0) throw new Error(`not a non-negative timestamp: ${value}`);
  return Math.floor(number);
}

// Contract week index of a unix timestamp in seconds: (ts + 3 days) / 1 week, Monday 00:00 UTC boundaries.
export function weekIndexOf(tsSeconds) {
  return Math.floor((toSeconds(tsSeconds) + WEEK_SHIFT_SECONDS) / WEEK_SECONDS);
}

// Unix seconds of Monday 00:00 UTC that starts week `index` (weekStart(w) = w * 1 weeks - 3 days).
export function weekStartOf(index) {
  const week = Number(index);
  if (!Number.isSafeInteger(week) || week < 1) throw new Error(`not a week index: ${index}`);
  return week * WEEK_SECONDS - WEEK_SHIFT_SECONDS;
}

// The off-chain key of a week index, always periodKeyFor('weekly', weekStart * 1000) (the board's key).
export function weekKeyOf(index) {
  return periodKeyFor('weekly', weekStartOf(index) * 1000);
}

// 'YYYY-Www' -> week index. Rejects keys that do not round-trip (for example 2026-W54).
export function weekIndexOfKey(key) {
  const match = /^(\d{4})-W(\d{2})$/.exec(String(key ?? ''));
  if (!match) throw new Error(`not an ISO week key (YYYY-Www): ${JSON.stringify(key)}`);
  const year = Number(match[1]);
  const week = Number(match[2]);
  // ISO week 1 is the week with January 4th; its Monday is the start of the ISO year.
  const jan4 = Date.UTC(year, 0, 4) / 1000;
  const jan4Day = new Date(jan4 * 1000).getUTCDay() || 7;
  const monday = jan4 - (jan4Day - 1) * 86400 + (week - 1) * WEEK_SECONDS;
  const index = weekIndexOf(monday);
  if (week < 1 || weekKeyOf(index) !== key) throw new Error(`no such ISO week: ${key}`);
  return index;
}

// The contract's weekBounds for an index and a cumulative admin extension (seconds).
export function weekBoundsOf(index, extensionSeconds = 0) {
  const start = weekStartOf(index);
  const close = start + WEEK_SECONDS;
  const shifted = close + Number(extensionSeconds);
  return {
    start,
    close,
    settleCutoff: shifted + SETTLE_GRACE_SECONDS,
    candidateUntil: shifted + CANDIDATE_WINDOW_SECONDS,
    payoutAt: shifted + PAYOUT_DELAY_SECONDS,
  };
}

