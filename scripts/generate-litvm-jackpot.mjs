// Generates apps/portal/src/generated/litvm-jackpot.mjs (Chikun Weekly Jackpot design §A.18) and holds the
// jackpot facts every jackpot tool shares: week math, rules (de)serialization and the deployment record.
//
// Two states:
//   * undeployed (while contracts/deployment-record.jackpot.json does not exist): status 'undeployed', null
//     addresses and an empty retired list. This is the committed state until runbook step E4.
//   * deployed (once the record exists): the active instance and every retired instance of the record,
//     which scripts/deploy-weekly-jackpot.mjs writes after a broadcast (it calls writeLitvmJackpotModule()).
//
// Usage:
//   node scripts/generate-litvm-jackpot.mjs                 # deployed if the record exists, else undeployed
//   node scripts/generate-litvm-jackpot.mjs --undeployed    # force the undeployed module
//   node scripts/generate-litvm-jackpot.mjs --check         # compare only; exit 1 when the file differs
//   --record <path> / --out <path>                          # other record / module paths (tests)
//
// Pure and offline: no RPC, no keys. The output is deterministic (lowercase addresses, fixed key order, a
// banner). It is a separate module from litvm-addresses.mjs, whose key set is pinned by
// tests/litvm-addresses-module.test.mjs. Server code imports it statically (so the Vercel tracer bundles
// it); browser initial chunks never import it (only the lazy jackpot chunks and the owner page do).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
