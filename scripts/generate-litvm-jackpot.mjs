const UNDEPLOYED = Object.freeze({ status: 'undeployed' });

function moduleToken(token) {
  return { address: token.address, symbol: token.symbol, decimals: token.decimals, name: token.name, testnet: token.testnet };
}

// null / { status: 'undeployed' } -> the undeployed export; a record -> the deployed export (plain object).
export function jackpotModuleValue(input = null) {
  if (input === null || input === undefined || input.status === 'undeployed') {
    return {
      status: 'undeployed',
      chainId: JACKPOT_CHAIN_ID,
      instances: {
        chikun: {
          address: null,
          startBlock: null,
          firstWeek: null,
          admin: null,
          keeper: null,
          residualRecipient: null,
          token: { address: null, symbol: null, decimals: null, name: null, testnet: null },
          retired: [],
        },
      },
    };
  }
  const record = normalizeJackpotRecord(input);
  const instance = record.instances.chikun;
  return {
    status: 'deployed',
    chainId: JACKPOT_CHAIN_ID,
    instances: {
      chikun: {
        address: instance.address,
        startBlock: instance.startBlock,
        firstWeek: instance.firstWeek,
        admin: instance.admin,
        keeper: instance.keeper,
        residualRecipient: instance.residualRecipient,
        token: moduleToken(instance.token),
        retired: instance.retired.map((entry) => ({
          address: entry.address,
          startBlock: entry.startBlock,
          firstWeek: entry.firstWeek,
          endAfterWeek: entry.endAfterWeek,
          token: moduleToken(entry.token),
        })),
      },
    },
  };
}

function literal(value) {
  if (value === null) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (typeof value !== 'string' || /[\\\n\r]/.test(value)) fail(`cannot render ${JSON.stringify(value)}`);
  return `'${value.replace(/'/g, "\\'")}'`;
}

function renderToken(token, indent) {
  return [
    `${indent}token: Object.freeze({`,
    ...['address', 'symbol', 'decimals', 'name', 'testnet'].map((key) => `${indent}  ${key}: ${literal(token[key])},`),
    `${indent}}),`,
  ];
}

// Pure: undeployed input or a jackpot record -> module source text.
export function renderLitvmJackpotModule(input = UNDEPLOYED) {
  const value = jackpotModuleValue(input);
  const chikun = value.instances.chikun;
  const retired = chikun.retired.length === 0
    ? ['      retired: Object.freeze([]),']
    : [
      '      retired: Object.freeze([',
      ...chikun.retired.flatMap((entry) => [
        '        Object.freeze({',
        ...['address', 'startBlock', 'firstWeek', 'endAfterWeek'].map((key) => `          ${key}: ${literal(entry[key])},`),
        ...renderToken(entry.token, '          '),
        '        }),',
      ]),
      '      ]),',
    ];
  return [
    JACKPOT_MODULE_BANNER,
    `// Status '${value.status}'. Regenerate with \`node scripts/generate-litvm-jackpot.mjs\` (design §A.18): undeployed`,
    '// until contracts/deployment-record.jackpot.json exists, then from that record. Server code imports it',
    '// statically; browser initial chunks never import it (only the lazy jackpot chunks and the owner page).',
    'export const LITVM_JACKPOT = Object.freeze({',
    `  status: ${literal(value.status)},`,
    `  chainId: ${value.chainId},`,
    '  instances: Object.freeze({',
    '    chikun: Object.freeze({',
    ...['address', 'startBlock', 'firstWeek', 'admin', 'keeper', 'residualRecipient'].map((key) => `      ${key}: ${literal(chikun[key])},`),
    ...renderToken(chikun.token, '      '),
    ...retired,
    '    }),',
    '  }),',
    '});',
    '',
  ].join('\n');
}

// Validates an imported LITVM_JACKPOT (the committed module or a --deployment override).
export function normalizeJackpotModule(value) {
  if (!value || typeof value !== 'object') fail('LITVM_JACKPOT is required');
  if (value.chainId !== JACKPOT_CHAIN_ID) fail(`LITVM_JACKPOT.chainId must be ${JACKPOT_CHAIN_ID}`);
  if (value.status === 'undeployed') return jackpotModuleValue(null);
  if (value.status !== 'deployed') fail(`LITVM_JACKPOT.status must be 'undeployed' or 'deployed'`);
  const chikun = value.instances?.chikun;
  if (!chikun) fail('LITVM_JACKPOT.instances.chikun is required');
  const token = (entry, label) => ({
    address: lowerAddress(entry?.address, `${label}.address`),
    symbol: text(entry?.symbol, `${label}.symbol`),
    decimals: safeInt(entry?.decimals, `${label}.decimals`),
    name: text(entry?.name, `${label}.name`),
    testnet: entry?.testnet === true,
  });
  return {
    status: 'deployed',
    chainId: JACKPOT_CHAIN_ID,
    instances: {
      chikun: {
        address: lowerAddress(chikun.address, 'chikun.address'),
        startBlock: safeInt(chikun.startBlock, 'chikun.startBlock'),
        firstWeek: safeInt(chikun.firstWeek, 'chikun.firstWeek', { min: 1 }),
        admin: lowerAddress(chikun.admin, 'chikun.admin'),
        keeper: lowerAddress(chikun.keeper, 'chikun.keeper', { nullable: true }),
        residualRecipient: lowerAddress(chikun.residualRecipient, 'chikun.residualRecipient'),
        token: token(chikun.token, 'chikun.token'),
        retired: (chikun.retired ?? []).map((entry, index) => ({
          address: lowerAddress(entry.address, `retired[${index}].address`),
          startBlock: safeInt(entry.startBlock, `retired[${index}].startBlock`),
          firstWeek: safeInt(entry.firstWeek, `retired[${index}].firstWeek`, { min: 1 }),
          endAfterWeek: safeInt(entry.endAfterWeek, `retired[${index}].endAfterWeek`, { min: 1 }),
          token: token(entry.token, `retired[${index}].token`),
        })),
      },
    },
  };
}

// Reads the record at `recordPath` (default: the committed record), or null when it does not exist.
export function readJackpotRecord({ root = repoRoot, recordPath = null } = {}) {
  const target = recordPath ? resolve(recordPath) : join(root, JACKPOT_RECORD_RELATIVE_PATH);
  if (!existsSync(target)) return null;
  return normalizeJackpotRecord(JSON.parse(readFileSync(target, 'utf8')));
}

// Writes a normalized record (2-space JSON + newline) and returns { path, record }.
export function writeJackpotRecord({ root = repoRoot, record, recordPath = null }) {
  const normalized = normalizeJackpotRecord(record);
  const target = recordPath ? resolve(recordPath) : join(root, JACKPOT_RECORD_RELATIVE_PATH);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `${JSON.stringify(normalized, null, 2)}\n`, 'utf8');
  return { path: target, record: normalized };
}

// mode 'auto' = deployed when a record is given or exists, 'undeployed' = always undeployed.
export function resolveJackpotModuleInput({ root = repoRoot, mode = 'auto', record = null, recordPath = null } = {}) {
  if (mode !== 'auto' && mode !== 'undeployed') fail(`unknown mode ${mode}`);
  if (mode === 'undeployed') return UNDEPLOYED;
  return record ?? readJackpotRecord({ root, recordPath }) ?? UNDEPLOYED;
}

// Writes the module and returns { path, relativePath, status, content, changed }.
export function writeLitvmJackpotModule({ root = repoRoot, mode = 'auto', record = null, recordPath = null, outPath = null } = {}) {
  const input = resolveJackpotModuleInput({ root, mode, record, recordPath });
  const content = renderLitvmJackpotModule(input);
  const target = outPath ? resolve(outPath) : join(root, JACKPOT_MODULE_RELATIVE_PATH);
  const previous = existsSync(target) ? readFileSync(target, 'utf8') : null;
  mkdirSync(dirname(target), { recursive: true });
  if (previous !== content) writeFileSync(target, content, 'utf8');
  return { path: target, relativePath: JACKPOT_MODULE_RELATIVE_PATH, status: jackpotModuleValue(input).status, content, changed: previous !== content };
}

// Compares a module file with what the record (or the undeployed state) renders.
export function checkLitvmJackpotModule({ root = repoRoot, mode = 'auto', record = null, recordPath = null, modulePath = null } = {}) {
  const input = resolveJackpotModuleInput({ root, mode, record, recordPath });
  const expected = renderLitvmJackpotModule(input);
  const target = modulePath ? resolve(modulePath) : join(root, JACKPOT_MODULE_RELATIVE_PATH);
  const actual = existsSync(target) ? readFileSync(target, 'utf8') : null;
  return { ok: actual === expected, status: jackpotModuleValue(input).status, path: target, expected, actual };
}

// Imports a generated module (default: the committed one) and returns its validated LITVM_JACKPOT.
export async function loadLitvmJackpot(modulePath = null) {
  const target = modulePath ? resolve(modulePath) : join(repoRoot, JACKPOT_MODULE_RELATIVE_PATH);
  const imported = await import(pathToFileURL(target).href);
  if (!imported.LITVM_JACKPOT) fail(`${target} does not export LITVM_JACKPOT`);
  return Object.freeze(normalizeJackpotModule(imported.LITVM_JACKPOT));
}

// CLI body, injectable for tests. Returns an exit code.
export function runGenerateJackpotCli({ argv = process.argv.slice(2), log = console.log, error = console.error, root = repoRoot } = {}) {
  const known = new Set(['--check', '--undeployed', '--record', '--out']);
  const recordAt = argv.indexOf('--record');
  const outAt = argv.indexOf('--out');
  const valueIndexes = new Set([recordAt + 1, outAt + 1].filter((index) => index > 0));
  const unknown = argv.filter((arg, index) => !valueIndexes.has(index) && !known.has(arg));
  if (unknown.length || (recordAt >= 0 && !argv[recordAt + 1]) || (outAt >= 0 && !argv[outAt + 1])) {
    error('usage: node scripts/generate-litvm-jackpot.mjs [--undeployed] [--check] [--record <path>] [--out <path>]');
    return 2;
  }
  const mode = argv.includes('--undeployed') ? 'undeployed' : 'auto';
  const recordPath = recordAt >= 0 ? argv[recordAt + 1] : null;
  const outPath = outAt >= 0 ? argv[outAt + 1] : null;
  if (argv.includes('--check')) {
    const result = checkLitvmJackpotModule({ root, mode, recordPath, modulePath: outPath });
    if (!result.ok) {
      error(`${outPath ?? JACKPOT_MODULE_RELATIVE_PATH} is out of date for status '${result.status}'. Run node scripts/generate-litvm-jackpot.mjs.`);
      return 1;
    }
    log(`${outPath ?? JACKPOT_MODULE_RELATIVE_PATH} is current (status '${result.status}').`);
    return 0;
  }
  const result = writeLitvmJackpotModule({ root, mode, recordPath, outPath });
  log(`${result.changed ? 'Wrote' : 'Unchanged'} ${outPath ?? result.relativePath} (status '${result.status}').`);
  return 0;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
  try {
    process.exitCode = runGenerateJackpotCli();
  } catch (err) {
    console.error(`generate-litvm-jackpot: ${err?.message ?? err}`);
    process.exitCode = 1;
  }
}
