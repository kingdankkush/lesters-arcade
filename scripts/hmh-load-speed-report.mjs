import { statSync, readdirSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HMH_LOAD_SPEED_BUDGETS = Object.freeze({
  mainBundleMaxBytes: 2_710_000,
  totalInitialJsMaxBytes: 2_900_000,
  sourceMapMaxCount: 0,
});

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function walkFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkFiles(full));
    else out.push(full);
  }
  return out;
}

function human(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

export function buildLoadSpeedReport({ repoRoot = repoRootFromHere() } = {}) {
  const portalRoot = path.join(repoRoot, 'apps', 'portal');
  const indexPath = path.join(portalRoot, 'index.html');
  const distDir = path.join(portalRoot, 'dist');
  const indexHtml = readFileSync(indexPath, 'utf8');
  const files = walkFiles(distDir);
  const jsFiles = files.filter((file) => file.endsWith('.js'));
  const mapFiles = files.filter((file) => file.endsWith('.map'));
  const mainPath = path.join(distDir, 'main.js');
  const mainBytes = existsSync(mainPath) ? statSync(mainPath).size : 0;
  const totalJsBytes = jsFiles.reduce((sum, file) => sum + statSync(file).size, 0);
  const initialEntrypoints = Object.freeze(['dist/main.js']);
  const checks = Object.freeze([
    Object.freeze({ id: 'uses-dist-bundle', pass: indexHtml.includes('src="./dist/main.js'), detail: 'index.html loads the optimized esbuild bundle instead of raw source main.js' }),
    Object.freeze({ id: 'modulepreload-main', pass: indexHtml.includes('rel="modulepreload" href="./dist/main.js'), detail: 'browser can start fetching the module graph from the head' }),
    Object.freeze({ id: 'keyart-preload', pass: indexHtml.includes('hard-money-heroes-keyart-bg.jpg') && indexHtml.includes('fetchpriority="high"'), detail: 'first-screen HMH key art is hinted as high-priority image' }),
    Object.freeze({ id: 'no-production-sourcemaps', pass: mapFiles.length <= HMH_LOAD_SPEED_BUDGETS.sourceMapMaxCount, detail: `${mapFiles.length} source maps emitted by default build` }),
    Object.freeze({ id: 'main-budget', pass: mainBytes > 0 && mainBytes <= HMH_LOAD_SPEED_BUDGETS.mainBundleMaxBytes, detail: `${human(mainBytes)} main bundle` }),
  ]);
  return Object.freeze({
    version: 'wo-36-load-speed-v1',
    budgets: HMH_LOAD_SPEED_BUDGETS,
    metrics: Object.freeze({
      mainBytes,
      totalJsBytes,
      jsFileCount: jsFiles.length,
      sourceMapCount: mapFiles.length,
      initialEntrypoints,
    }),
    checks,
    summary: Object.freeze({
      status: checks.every((check) => check.pass) ? 'PASS' : 'FAIL',
      passCount: checks.filter((check) => check.pass).length,
      checkCount: checks.length,
    }),
  });
}

export function renderLoadSpeedMarkdown(report = buildLoadSpeedReport()) {
  const rows = report.checks.map((check) => `| ${check.id} | ${check.pass ? 'PASS' : 'FAIL'} | ${check.detail} |`).join('\n');
  return `# Hard Money Heroes Load-Speed Optimization Pass\n\nGenerated by \`scripts/hmh-load-speed-report.mjs\`.\n\n## Summary\n\n- Version: ${report.version}\n- Status: ${report.summary.status}\n- Main bundle: ${human(report.metrics.mainBytes)}\n- Total emitted JS: ${human(report.metrics.totalJsBytes)} across ${report.metrics.jsFileCount} files\n- Source maps emitted by default: ${report.metrics.sourceMapCount}\n- Initial entrypoints: ${report.metrics.initialEntrypoints.join(', ')}\n\n| Check | Status | Detail |\n| --- | --- | --- |\n${rows}\n`;
}

export function writeLoadSpeedReport({ repoRoot = repoRootFromHere() } = {}) {
  const report = buildLoadSpeedReport({ repoRoot });
  const outDir = path.join(repoRoot, 'docs', 'performance');
  mkdirSync(outDir, { recursive: true });
  const jsonPath = path.join(outDir, 'hard-money-heroes-load-speed.json');
  const mdPath = path.join(outDir, 'hard-money-heroes-load-speed.md');
  writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderLoadSpeedMarkdown(report), 'utf8');
  return Object.freeze({ report, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { report, jsonPath, mdPath } = writeLoadSpeedReport();
  console.log(`HMH load-speed report written: ${jsonPath}`);
  console.log(`HMH load-speed markdown written: ${mdPath}`);
  console.log(`Status: ${report.summary.status}; main ${human(report.metrics.mainBytes)}; maps ${report.metrics.sourceMapCount}`);
  if (report.summary.status !== 'PASS') process.exitCode = 1;
}
