// Runs test files in `cwd` with the detail reporter → [{ file, name, message, expected, actual, line, source }]
function failingTestsIn(cwd, files, reporterPath) {
  if (!files.length) return { failures: [], exitCode: 0 };
  const result = spawnSync(process.execPath, ['--test', '--test-concurrency=1', `--test-reporter=${pathToFileURL(reporterPath).href}`, ...files], { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, timeout: 30 * 60_000 });
  const failures = [];
  for (const line of String(result.stdout ?? '').split(/\r?\n/)) {
    if (!line.trim()) continue;
    let event;
    try { event = JSON.parse(line); } catch { continue; }
    if (event.nesting !== 0) continue;
    const file = relative(cwd, event.file ?? '').split(sep).join('/');
    const lineNumber = testLineFromStack(event.stack, file);
    let source = null;
    if (lineNumber) {
      try { source = readFileSync(join(cwd, file), 'utf8').split(/\r?\n/)[lineNumber - 1]?.trim() ?? null; } catch {}
    }
    failures.push({ file, name: event.name, message: redact(event.message).slice(0, 600), expected: event.expected ?? null, actual: event.actual ?? null, line: lineNumber, source });
  }
  return { failures, exitCode: result.status };
}

