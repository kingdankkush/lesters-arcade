export async function runStep7DryRun({ argv = process.argv.slice(2), log = console.log, repoRoot = root } = {}) {
  const guard = checkGuards({ argv, ...gitDirs(repoRoot) });
  if (!guard.ok) {
    log(guard.error);
    return 2;
  }
  const stepsFlag = argv.includes('--steps') ? argv[argv.indexOf('--steps') + 1] : null;
  // Development aid: run only these test files (comma list) instead of the build steps and the gate.
  // The report is then marked partial and must not be committed.
  const testsFlag = argv.includes('--tests') ? argv[argv.indexOf('--tests') + 1] : null;
  const fullVerify = !argv.includes('--no-full-verify');
  const before = porcelain(repoRoot);
  const head = git(['rev-parse', '--short', 'HEAD'], repoRoot);
  const pkg = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
  let buildSteps = splitNpmScript(pkg.scripts['vercel:build']);
  if (stepsFlag) buildSteps = buildSteps.filter((step) => stepsFlag.split(',').includes(step.id));
  if (testsFlag) buildSteps = [];
  const base = mkdtempSync(join(tmpdir(), 'lesters-step7-'));
  const wt = join(base, 'wt');
  const reporter = join(base, 'step7-reporter.mjs');
  writeFileSync(reporter, REPORTER_SOURCE, 'utf8');
  const junctions = [];
  const report = {
    schema: STEP7_REPORT_SCHEMA,
    generatedAt: new Date().toISOString(),
    head,
    command: 'node scripts/rehearse-step7-dry-run.mjs --confirm-throwaway',
    note: 'Throwaway worktree under the OS temp directory, removed at the end. Nothing was committed, pushed or deployed; the deployment record is a local Hardhat deploy.',
  };
  log(`step-7 dry run: throwaway worktree at ${wt} (HEAD ${head})`);
  git(['worktree', 'add', '--detach', wt, 'HEAD'], repoRoot);
  try {
    junctions.push(junction(join(repoRoot, 'node_modules'), join(wt, 'node_modules')));
    junctions.push(junction(join(repoRoot, 'benchmarks', 'hmh-engine-bakeoff', 'node_modules'), join(wt, 'benchmarks', 'hmh-engine-bakeoff', 'node_modules')));

    // 1. Local deploy → record → deployed address module.
    log('1. local deploy, deployment record, address module (deployed)');
    const record = await deployLocalRecord(repoRoot);
    writeFileSync(join(wt, RECORD_RELATIVE_PATH), `${JSON.stringify(record, null, 2)}\n`, 'utf8');
    const generate = run('node scripts/generate-litvm-addresses.mjs --deployed', wt);
    if (generate.exitCode !== 0) throw new Error(`generate-litvm-addresses failed: ${tail(generate.output, 5).join(' | ')}`);
    const moduleText = readFileSync(join(wt, ADDRESS_MODULE_RELATIVE_PATH), 'utf8');
    report.addressModule = {
      status: /status: 'deployed'/.test(moduleText) ? 'deployed' : 'unexpected',
      startBlock: record.startBlock,
      deployer: record.deployer.toLowerCase(),
      addresses: record.addresses,
      note: 'Deployed on the in-process chain from the real deployer address (impersonated) at nonce 0, so the addresses equal the §8.1 prediction.',
    };

    // 2. Flags.
    log('2. flags');
    report.flagEdits = applyEdits(wt, FLAG_EDITS);
    if (!report.flagEdits.every((edit) => edit.applied)) throw new Error('the flag literals were not found exactly once in settlement.mjs');
    const afterFlags = porcelain(wt).map((entry) => entry.path);

    // 3. Portal pages.
    log('3. node scripts/build-portal-pages.mjs');
    const pages = run('node scripts/build-portal-pages.mjs', wt);
    const afterPages = porcelain(wt);
    report.generated = {
      buildPortalPages: { exitCode: pages.exitCode, output: tail(pages.output, 10) },
      changedByDeploy: afterFlags.filter((path) => path !== SETTLEMENT_RELATIVE_PATH),
      changedByFlags: [SETTLEMENT_RELATIVE_PATH],
      changedByPortalPages: afterPages.map((entry) => entry.path).filter((path) => !afterFlags.includes(path)),
      diffStat: tail(git(['diff', '--stat'], wt), 60),
    };
    const flippedPatch = git(['diff', '--binary'], wt);

    // 4. vercel:build steps and the offline audits, continuing past failures.
    const steps = [];
    for (const step of testsFlag ? [] : [...buildSteps, ...EXTRA_AUDITS]) {
      log(`4. ${step.command}`);
      const result = run(step.command, wt);
      steps.push({ id: step.id, command: step.command, exitCode: result.exitCode, ms: result.ms, inVercelBuild: buildSteps.includes(step), output: tail(result.output, 25) });
      log(`   exit ${result.exitCode} in ${Math.round(result.ms / 1000)} s`);
    }
    const gatePath = join(wt, GATE_REPORT_RELATIVE_PATH);
    const gate = testsFlag ? null : (existsSync(gatePath) ? JSON.parse(readFileSync(gatePath, 'utf8')) : null);
    const parsed = parseGateErrors(gate?.errors ?? []);
    if (testsFlag) {
      report.partial = `only ${testsFlag}`;
      cleanBuildOutput(wt);
      for (const failure of failingTestsIn(wt, testsFlag.split(','), reporter).failures) parsed.unexpected.push({ file: failure.file, name: failure.name });
    }
    report.gate = { status: gate?.status ?? 'not-run', counts: gate?.counts ?? null, expectedFailureCount: gate?.expectedFailureCount ?? null, unexpected: parsed.unexpected.length, missing: parsed.missing.length, other: parsed.other };

    // Failure details in the flipped tree.
    const failingFiles = [...new Set([...parsed.unexpected, ...parsed.missing].map((failure) => failure.file))];
    log(`5. failure details (${parsed.unexpected.length} unexpected, ${parsed.missing.length} missing in ${failingFiles.length} file(s))`);
    const flipped = failingTestsIn(wt, failingFiles, reporter);

    // 5. Baseline: the same files and failing steps on the unflipped tree. The build output is
    // removed before every test run, as the release gate runs before `npm run build`.
    const stepsPatch = git(['diff', '--binary'], wt);
    git(['checkout', '--', '.'], wt);
    rmSync(join(wt, RECORD_RELATIVE_PATH), { force: true });
    cleanBuildOutput(wt);
    const baseline = failingTestsIn(wt, failingFiles, reporter);
    const baselineKeys = new Set(baseline.failures.map((failure) => `${failure.file} :: ${failure.name}`));
    for (const step of steps) {
      if (step.exitCode === 0 || step.id === 'test:release') {
        step.causedByStep7 = false;
        continue;
      }
      const again = run(step.command, wt);
      step.baselineExitCode = again.exitCode;
      step.causedByStep7 = again.exitCode === 0;
    }
    const testRelease = steps.find((step) => step.id === 'test:release');
    if (testRelease) testRelease.causedByStep7 = parsed.unexpected.some((failure) => !baselineKeys.has(`${failure.file} :: ${failure.name}`));
    report.steps = steps;
    const detailFor = (failure) => flipped.failures.find((item) => item.file === failure.file && item.name === failure.name) ?? null;
    report.failures = {
      causedByStep7: parsed.unexpected.filter((failure) => !baselineKeys.has(`${failure.file} :: ${failure.name}`)).map((failure) => ({ ...failure, ...(detailFor(failure) ?? {}) })),
      preExisting: parsed.unexpected.filter((failure) => baselineKeys.has(`${failure.file} :: ${failure.name}`)).map((failure) => ({ ...failure, note: 'fails at the dry-run base too' })),
      missingLedger: parsed.missing,
    };

    // 6. Re-apply the flipped tree (with the steps' own outputs), then the step-7 edits, and prove them.
    git(['checkout', '--', '.'], wt);
    const patch = stepsPatch || flippedPatch;
    const patchFile = join(base, 'flipped.patch');
    writeFileSync(patchFile, `${patch}\n`, 'utf8');
    if (patch.trim()) git(['apply', '--whitespace=nowarn', patchFile], wt);
    writeFileSync(join(wt, RECORD_RELATIVE_PATH), `${JSON.stringify(record, null, 2)}\n`, 'utf8');
    cleanBuildOutput(wt);
    const edits = applyEdits(wt, STEP7_TEST_EDITS);
    const targets = [...new Set([...report.failures.causedByStep7.map((failure) => failure.file), ...edits.map((edit) => edit.file).filter((file) => file.startsWith('tests/'))])];
    const verified = failingTestsIn(wt, targets, reporter);
    const stillFailing = verified.failures.filter((failure) => report.failures.causedByStep7.some((item) => item.file === failure.file && item.name === failure.name) || edits.some((edit) => edit.file === failure.file));
    report.step7Edits = edits.map((edit) => ({ ...edit, verified: edit.applied && !stillFailing.some((failure) => failure.file === edit.file) }));
    report.unexplainedFailures = stillFailing.map((failure) => ({ file: failure.file, name: failure.name, message: failure.message, line: failure.line, source: failure.source }));
    for (const step of steps.filter((entry) => entry.causedByStep7 && entry.id !== 'test:release')) {
      const again = run(step.command, wt);
      step.afterEditsExitCode = again.exitCode;
    }
    if (fullVerify) {
      log('6. full release gate after the step-7 edits');
      cleanBuildOutput(wt);
      const full = run('npm run test:release', wt);
      const fullGate = existsSync(gatePath) ? JSON.parse(readFileSync(gatePath, 'utf8')) : null;
      const fullParsed = parseGateErrors(fullGate?.errors ?? []);
      report.fullVerify = { exitCode: full.exitCode, status: fullGate?.status ?? 'not-run', counts: fullGate?.counts ?? null, unexpected: fullParsed.unexpected.length, missing: fullParsed.missing.length, unexpectedFailures: fullParsed.unexpected };
    }
    report.ok = report.unexplainedFailures.length === 0 && report.step7Edits.every((edit) => edit.verified)
      && steps.filter((step) => step.causedByStep7 && step.id !== 'test:release').every((step) => step.afterEditsExitCode === 0);
  } finally {
    for (const path of junctions.filter(Boolean)) removeJunction(path);
    git(['worktree', 'remove', '--force', wt], repoRoot, { allowFail: true });
    git(['worktree', 'prune'], repoRoot, { allowFail: true });
    rmSync(base, { recursive: true, force: true });
  }
  report.throwawayRemoved = !existsSync(wt);

  const reportPath = join(repoRoot, STEP7_REPORT_RELATIVE_PATH);
  mkdirSync(dirname(reportPath), { recursive: true });
  writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  const docPath = join(repoRoot, STEP7_DOC_RELATIVE_PATH);
  writeFileSync(docPath, upsertChecklist(readFileSync(docPath, 'utf8'), renderChecklist(report)), 'utf8');
  const after = porcelain(repoRoot);
  const traces = after.filter((entry) => !before.some((item) => item.path === entry.path) && ![STEP7_REPORT_RELATIVE_PATH, STEP7_DOC_RELATIVE_PATH].includes(entry.path));
  log(`step-7 dry run ${report.ok ? 'PASS' : 'NEEDS ATTENTION'}: ${report.failures.causedByStep7.length} failure(s) caused by the flip, ${report.step7Edits.length} edit(s), ${report.unexplainedFailures.length} unexplained.`);
  log(`report: ${STEP7_REPORT_RELATIVE_PATH}; checklist: ${STEP7_DOC_RELATIVE_PATH}`);
  if (traces.length) {
    log(`WARNING: unexpected files changed in this worktree: ${traces.map((entry) => entry.path).join(', ')}`);
    return 1;
  }
  return report.ok ? 0 : 1;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
  try {
    process.exitCode = await runStep7DryRun();
  } catch (error) {
    console.error(`rehearse-step7-dry-run: ${error?.name ?? 'Error'}: ${error?.message ?? error}`);
    process.exitCode = 1;
  }
}
