// Guards.

export function checkGuards({ argv = [], gitDir, commonDir }) {
  if (!argv.includes('--confirm-throwaway')) {
    return { ok: false, error: 'refused: pass --confirm-throwaway (the dry run creates and deletes a temporary git worktree under the OS temp directory)' };
  }
  if (!gitDir || !commonDir) return { ok: false, error: 'refused: not inside a git worktree' };
  if (resolve(gitDir).toLowerCase() === resolve(commonDir).toLowerCase()) {
    return { ok: false, error: 'refused: this is the repository\'s main worktree; run the dry run from a slice worktree' };
  }
  return { ok: true, error: null };
}

function git(args, cwd, { allowFail = false, raw = false } = {}) {
  const result = spawnSync('git', args, { cwd, encoding: raw ? 'buffer' : 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (!allowFail && result.status !== 0) throw new Error(`git ${args[0]} failed (${result.status}): ${String(result.stderr).trim().split('\n').slice(-3).join(' | ')}`);
  if (raw) return result.status === 0 ? result.stdout : null;
  // Trim the end only: `git status --porcelain` starts lines with a significant space.
  return String(result.stdout ?? '').trimEnd();
}

export function gitDirs(cwd) {
  const gitDir = resolve(cwd, git(['rev-parse', '--git-dir'], cwd));
  const commonDir = resolve(cwd, git(['rev-parse', '--git-common-dir'], cwd));
  return { gitDir, commonDir };
}

