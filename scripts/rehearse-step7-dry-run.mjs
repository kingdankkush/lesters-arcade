// A tree state relative to HEAD: the tracked diff and every untracked file's bytes.
function captureState(wt) {
  const untracked = new Map();
  for (const entry of porcelain(wt).filter((item) => item.status === '??')) untracked.set(entry.path, readFileSync(join(wt, entry.path)));
  return { patch: git(['diff', '--binary'], wt, { raw: true }), untracked };
}

function resetToHead(wt) {
  git(['checkout', '--', '.'], wt);
  for (const entry of porcelain(wt).filter((item) => item.status === '??')) rmSync(join(wt, entry.path), { force: true });
  cleanBuildOutput(wt);
}

function restoreState(wt, state, base) {
  resetToHead(wt);
  if (state.patch && state.patch.length) {
    const patchFile = join(base, 'state.patch');
    writeFileSync(patchFile, state.patch);
    git(['apply', '--whitespace=nowarn', '--binary', patchFile], wt);
  }
  for (const [path, bytes] of state.untracked) {
    mkdirSync(dirname(join(wt, path)), { recursive: true });
    writeFileSync(join(wt, path), bytes);
  }
  cleanBuildOutput(wt);
}

// The deployment record step 3 will produce, rehearsed: contracts/deploy-config.testnet.json as is,
// deployed on the in-process chain from the REAL deployer address (impersonated: no key exists here)
// at its nonce 0, so every address equals the §8.1 prediction and the roles are the real ones. Only
// deployedAt, the blocks and the transaction hashes differ from the LiteForge broadcast.
async function deployLocalRecord(repoRoot) {
  const { activateLocalGames, deployLocalSuite, startLocalChain } = await import('./lib/local-chain.mjs');
  const config = JSON.parse(readFileSync(join(repoRoot, 'contracts', 'deploy-config.testnet.json'), 'utf8'));
  const chain = await startLocalChain();
  try {
    const deployer = await chain.impersonate(config.deployer);
    const developer = await chain.impersonate(config.developerWallet);
    const record = await deployLocalSuite({ provider: chain.provider, wallets: { operator: deployer }, config });
    await activateLocalGames({ provider: chain.provider, record, developer, operator: deployer });
    return record;
  } finally {
    await chain.close();
  }
}

// Step 3's files: the record and the module regenerated from it (the exact command the checklist names).
function applyStep3(wt, record) {
  writeFileSync(join(wt, RECORD_RELATIVE_PATH), `${JSON.stringify(record, null, 2)}\n`, 'utf8');
  const generate = run(ADDRESS_COMMAND, wt);
  if (generate.exitCode !== 0) throw new Error(`${ADDRESS_COMMAND} failed: ${tail(generate.output, 5).join(' | ')}`);
  return readFileSync(join(wt, ADDRESS_MODULE_RELATIVE_PATH), 'utf8');
}

function applyEdits(wt, edits) {
  const results = [];
  const originals = new Map();
  for (const item of edits) {
    const path = join(wt, item.file);
    const text = readFileSync(path, 'utf8');
    if (!originals.has(item.file)) originals.set(item.file, text);
    const applied = applyTextEdit(text, item);
    if (applied.ok) writeFileSync(path, applied.text, 'utf8');
    const line = applied.ok ? lineOf(originals.get(item.file), item.find) : null;
    results.push({ file: item.file, line, before: item.find, after: item.replace, reason: item.reason ?? null, applied: applied.ok, error: applied.error });
  }
  return results;
}

// Runs AUDITS in order → { results: [{ id, command, exitCode, ms, output, wrote }], texts }. `wrote` is
// every path whose content that audit changed; `texts` is every dirty path's content afterwards.
function runAudits(wt, log, label) {
  const results = [];
  for (const audit of AUDITS) {
    log(`   ${label}: ${audit.command}`);
    const before = dirtyTexts(wt);
    const result = run(audit.command, wt);
    const after = dirtyTexts(wt);
    const wrote = [...after.keys()].filter((path) => !before.has(path) || before.get(path) !== after.get(path));
    const committedAgain = [...before.keys()].filter((path) => !after.has(path));
    results.push({ id: audit.id, command: audit.command, exitCode: result.exitCode, ms: result.ms, output: tail(result.output, 12), wrote: [...wrote, ...committedAgain].sort(), ...(audit.checks ? { checks: [...audit.checks] } : {}) });
  }
  return { results, texts: dirtyTexts(wt) };
}

// Runs the release gate (or, in development mode, only the given test files) → { gate, parsed }.
function runGate(wt, { testsFlag, reporter }) {
  cleanBuildOutput(wt);
  if (testsFlag) {
    const failures = failingTestsIn(wt, testsFlag.split(','), reporter).failures;
    return { gate: { status: 'partial', counts: null, expectedFailureCount: null }, parsed: { unexpected: failures.map((failure) => ({ file: failure.file, name: failure.name })), missing: [], other: [] }, exitCode: null, ms: null, output: [] };
  }
  const result = run('npm run test:release', wt);
  const gatePath = join(wt, GATE_REPORT_RELATIVE_PATH);
  const gate = existsSync(gatePath) ? JSON.parse(readFileSync(gatePath, 'utf8')) : null;
  return { gate, parsed: parseGateErrors(gate?.errors ?? []), exitCode: result.exitCode, ms: result.ms, output: tail(result.output, 25) };
}

const gateSummary = (gate, parsed) => ({ status: gate?.status ?? 'not-run', counts: gate?.counts ?? null, expectedFailureCount: gate?.expectedFailureCount ?? null, unexpected: parsed.unexpected.length, missing: parsed.missing.length, other: parsed.other });
const keyOf = (failure) => `${failure.file} :: ${failure.name}`;

// Failures in the new state that are not failures in the previous one are caused by the step.
function classifyFailures(parsed, previous, details) {
  const previousKeys = new Set(previous.failures.map(keyOf));
  const detailFor = (failure) => details.failures.find((item) => item.file === failure.file && item.name === failure.name) ?? null;
  return {
    caused: parsed.unexpected.filter((failure) => !previousKeys.has(keyOf(failure))).map((failure) => ({ ...failure, ...(detailFor(failure) ?? {}) })),
    preExisting: parsed.unexpected.filter((failure) => previousKeys.has(keyOf(failure))).map((failure) => ({ file: failure.file, name: failure.name, note: 'fails before this step too' })),
    missingLedger: parsed.missing,
  };
}

// Proves a commit's applied test edits: every failure the step caused, and every edited file, must
// pass afterwards.
function proveEdits(wt, applied, caused, reporter) {
  cleanBuildOutput(wt);
  const targets = [...new Set([...caused.map((failure) => failure.file), ...applied.map((item) => item.file).filter((file) => file.startsWith('tests/'))])];
  const verified = failingTestsIn(wt, targets, reporter);
  const stillFailing = verified.failures.filter((failure) => caused.some((item) => item.file === failure.file && item.name === failure.name) || applied.some((item) => item.file === failure.file));
  return {
    edits: applied.map((item) => ({ ...item, verified: item.applied && !stillFailing.some((failure) => failure.file === item.file) })),
    unexplainedFailures: stillFailing.map((failure) => ({ file: failure.file, name: failure.name, message: failure.message, line: failure.line, source: failure.source })),
  };
}

// Generated documents whose content differs between two states' audit runs. `wroteBy` maps each path
// any audit wrote (in any state) to the audit that wrote it.
function generatedChanges({ from, to, wroteBy, committed, exclude = [] }) {
  const out = [];
  for (const [path, by] of wroteBy) {
    if (exclude.includes(path)) continue;
    const before = from.has(path) ? from.get(path) : committed(path);
    const after = to.has(path) ? to.get(path) : committed(path);
    if (before === after) continue;
    out.push({ path, by, ...lineChanges(before, after) });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

// ---------------------------------------------------------------------------
// Checklist rendering (pure).

function renderEdits(out, edits, code) {
  for (const item of edits) {
    const where = `${code(`${item.file}${item.line ? `:${item.line}` : ''}`)}${item.reason ? ` (${item.reason})` : ''}${item.verified ? '' : ' **(NOT verified)**'}`;
    if (!item.before.includes(NEWLINE) && !item.after.includes(NEWLINE)) {
      out.push(`   - ${where}: ${code(item.before.trim())} → ${code(item.after.trim())}`);
      continue;
    }
    out.push(`   - ${where}:`);
    out.push('     ```diff');
    for (const line of item.before.split(NEWLINE)) out.push(`     -${line}`);
    for (const line of item.after.split(NEWLINE)) out.push(`     +${line}`);
    out.push('     ```');
  }
}

function renderUnexplained(out, unexplained, code) {
  if (!unexplained.length) return;
  out.push(`   - **NOT COVERED** (this dry run did not pass; ${unexplained.length} failure${unexplained.length === 1 ? '' : 's'} caused by the step still fail):`);
  for (const failure of unexplained) out.push(`     - ${code(`${failure.file}${failure.line ? `:${failure.line}` : ''} :: ${failure.name}`)}`);
}

function renderGenerated(out, docs, code) {
  const byCommand = new Map();
  for (const doc of docs) {
    if (!byCommand.has(doc.by)) byCommand.set(doc.by, []);
    byCommand.get(doc.by).push(doc);
  }
  for (const [command, list] of byCommand) {
    out.push(`   - ${code(command)} rewrites ${list.map((doc) => code(doc.path)).join(', ')}:`);
    const sample = list.flatMap((doc) => [...doc.removed.slice(0, 2).map((line) => `-${line}`), ...doc.added.slice(0, 2).map((line) => `+${line}`)]).slice(0, 8);
    if (!sample.length) continue;
    out.push('     ```diff');
    for (const line of sample) out.push(`     ${line.length > 160 ? `${line.slice(0, 159)}…` : line}`);
    out.push('     ```');
  }
}

