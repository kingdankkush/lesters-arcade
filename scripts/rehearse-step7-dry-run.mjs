// Edits and parsing (pure).

export function applyTextEdit(text, { find, replace }) {
  const first = text.indexOf(find);
  if (first < 0) return { ok: false, text, error: 'find text not present' };
  if (text.indexOf(find, first + find.length) >= 0) return { ok: false, text, error: 'find text is not unique' };
  return { ok: true, text: text.slice(0, first) + replace + text.slice(first + find.length), error: null };
}

// Gate report errors → { unexpected: [{file, name}], missing: [{file, name}], other: [text] }
export function parseGateErrors(errors = []) {
  const unexpected = [];
  const missing = [];
  const other = [];
  for (const line of errors) {
    const match = /^(unexpected failure|missing ledger failure): (.+?) :: (.+)$/.exec(String(line));
    if (!match) {
      other.push(String(line));
      continue;
    }
    (match[1] === 'unexpected failure' ? unexpected : missing).push({ file: match[2], name: match[3] });
  }
  return { unexpected, missing, other };
}

export function splitNpmScript(command) {
  return String(command).split('&&').map((part) => part.trim()).filter(Boolean).map((part) => {
    const match = /^npm run ([A-Za-z0-9:_-]+)$/.exec(part);
    return { id: match ? match[1] : part, command: part };
  });
}

// The first stack frame inside `file` (a test file) → its line number.
export function testLineFromStack(stack, file) {
  const name = String(file).split(/[\\/]/).pop().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = new RegExp(`${name}:(\\d+):\\d+`).exec(String(stack ?? ''));
  return match ? Number(match[1]) : null;
}

const redact = (text) => String(text ?? '').replace(HEX_OR_KEY, (hex) => `${hex.slice(0, 10)}…`);
const tail = (text, lines = 40) => redact(String(text ?? '').replace(/\u001b\[[0-9;]*m/g, '')).split(/\r?\n/).filter((line) => line.trim()).slice(-lines);

