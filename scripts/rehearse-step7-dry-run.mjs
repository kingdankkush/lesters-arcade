export function applyTextEdit(text, { find, replace }) {
  const first = text.indexOf(find);
  if (first < 0) return { ok: false, text, error: 'find text not present' };
  if (text.indexOf(find, first + find.length) >= 0) return { ok: false, text, error: 'find text is not unique' };
  return { ok: true, text: text.slice(0, first) + replace + text.slice(first + find.length), error: null };
}

// Gate report errors → { unexpected: [{file, name}], missing: [{file, name}], other: [text] }
export function parseGateErrors(errors = []) {
  const unexpected = [];
  const missing = [];
  const other = [];
  for (const line of errors) {
    const match = /^(unexpected failure|missing ledger failure): (.+?) :: (.+)$/.exec(String(line));
    if (!match) {
      other.push(String(line));
      continue;
    }
    (match[1] === 'unexpected failure' ? unexpected : missing).push({ file: match[2], name: match[3] });
  }
  return { unexpected, missing, other };
}

export function splitNpmScript(command) {
  return String(command).split('&&').map((part) => part.trim()).filter(Boolean).map((part) => {
    const match = /^npm run ([A-Za-z0-9:_-]+)$/.exec(part);
    return { id: match ? match[1] : part, command: part };
  });
}

// The first stack frame inside `file` (a test file) → its line number.
export function testLineFromStack(stack, file) {
  const name = String(file).split(/[\\/]/).pop().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = new RegExp(`${name}:(\\d+):\\d+`).exec(String(stack ?? ''));
  return match ? Number(match[1]) : null;
}

// Line numbers refer to each file as it stands before the edits of that commit (for both commits
// that is the file as committed at the dry-run head: no step-7 edit touches a step-3 file).
export function lineOf(text, find) {
  const at = text.indexOf(find);
  return at < 0 ? null : text.slice(0, at).split(NEWLINE).length;
}

// A replacer for local absolute paths: each [path, label] in every spelling a tool may print (as is,
// with forward slashes, with backslashes, with JSON-doubled backslashes), case-insensitively; the
// longest paths first so the throwaway worktree wins over the temp directory and the home directory.
export function pathScrubber(pairs) {
  const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const rules = [];
  for (const [path, label] of pairs) {
    if (!path) continue;
    const plain = String(path).replace(/[\\/]+$/, '');
    const forward = plain.replaceAll('\\', '/');
    const back = forward.replaceAll('/', '\\');
    for (const spelling of new Set([plain, forward, back, back.replaceAll('\\', '\\\\')])) rules.push({ length: spelling.length, re: new RegExp(escape(spelling), 'gi'), label });
  }
  rules.sort((a, b) => b.length - a.length);
  return (text) => rules.reduce((out, rule) => out.replace(rule.re, rule.label), String(text ?? ''));
}

let scrub = (text) => String(text ?? '');
const redact = (text) => scrub(text).replace(HEX_OR_KEY, (hex) => `${hex.slice(0, 10)}…`);
const tail = (text, count = 40) => redact(String(text ?? '').replace(/\u001b\[[0-9;]*m/g, '')).split(/\r?\n/).filter((line) => line.trim()).slice(-count);
const normalizedOutput = (text) => tail(text, 400).join('\n').replace(/\b\d+(\.\d+)?\s?(ms|s)\b/g, '<t>');

export function sha256Text(text) {
  return createHash('sha256').update(String(text).replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

// Lines removed from `before` and added in `after` (multiset difference), at most `limit` each, the
// telling ones first (a changed input hash or byte count says less than a changed state line).
const BOOKKEEPING_LINE = /[0-9a-f]{40,}|"bytes"\s*:|\|\s*\d+\s*\|\s*$/i;
export function lineChanges(before, after, { limit = 6, width = 200 } = {}) {
  const count = (text) => {
    const map = new Map();
    for (const line of String(text ?? '').split(/\r?\n/)) if (line.trim()) map.set(line, (map.get(line) ?? 0) + 1);
    return map;
  };
  const a = count(before);
  const b = count(after);
  const minus = (x, y) => [...x.entries()].flatMap(([line, n]) => Array(Math.max(0, n - (y.get(line) ?? 0))).fill(line));
  const telling = (list) => [...list.filter((line) => !BOOKKEEPING_LINE.test(line)), ...list.filter((line) => BOOKKEEPING_LINE.test(line))];
  const cut = (list) => telling(list).slice(0, limit).map((line) => redact(line.trim()).slice(0, width));
  const removed = minus(a, b);
  const added = minus(b, a);
  return { removed: cut(removed), added: cut(added), removedCount: removed.length, addedCount: added.length };
}

