function junction(target, path) {
  if (!existsSync(target)) return null;
  mkdirSync(dirname(path), { recursive: true });
  symlinkSync(realpathSync(target), path, 'junction');
  return path;
}

function removeJunction(path) {
  try {
    if (lstatSync(path).isSymbolicLink()) unlinkSync(path);
  } catch {}
}

function run(command, cwd, { timeoutMs = 45 * 60_000 } = {}) {
  const started = Date.now();
  const result = spawnSync(command, { cwd, shell: true, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, timeout: timeoutMs, env: { ...process.env, FORCE_COLOR: '0', NO_COLOR: '1' } });
  return { command, exitCode: result.status, signal: result.signal ?? null, ms: Date.now() - started, output: `${result.stdout ?? ''}\n${result.stderr ?? ''}` };
}

