import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { HMH_SFX_MANIFEST } from '../apps/portal/assets/audio/sfx/sfx-manifest.mjs';
import { HMH_AUDIO_MIX, HMH_SFX_CUE_REGISTRY, validateHmhAudioSystem } from '../apps/portal/src/hmh-audio-system.mjs';
import { COMBAT_FEEDBACK_MOMENTS } from '../apps/portal/src/hmh-combat-feedback.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

function registryRows() {
  return Object.entries(HMH_SFX_CUE_REGISTRY).map(([cue, spec]) => [
    cue,
    spec.family,
    spec.priority,
    spec.cooldownMs,
    spec.samplePreferred ? 'sample + synth' : 'synth fallback',
    spec.tone.join('/'),
  ]);
}

export function buildHmhAudioSystemReport() {
  const manifestCues = Object.keys(HMH_SFX_MANIFEST.cues ?? {});
  const feedbackCues = Object.values(COMBAT_FEEDBACK_MOMENTS).map((moment) => moment.cues.sfxCue);
  const validation = validateHmhAudioSystem({ manifestCues, runtimeCues: feedbackCues });
  return Object.freeze({
    version: HMH_AUDIO_MIX.version,
    validation,
    mix: HMH_AUDIO_MIX,
    manifestCueCount: manifestCues.length,
    feedbackCueCount: new Set(feedbackCues).size,
    registry: HMH_SFX_CUE_REGISTRY,
  });
}

export function renderHmhAudioSystemMarkdown(report = buildHmhAudioSystemReport()) {
  return `# Hard Money Heroes Audio and SFX System\n\nGenerated by \`scripts/hmh-audio-system-report.mjs\`.\n\n## Summary\n\n- Version: ${report.version}\n- Status: ${report.validation.ok ? 'PASS' : 'FAIL'}\n- Registered cues: ${report.validation.cueCount}\n- Global SFX voice cap: ${report.mix.maxVoices}\n- Voice policy: runtime-enforced family caps with priority-safe oldest-voice stealing\n- CC0 sample cues: ${report.manifestCueCount}\n- Combat-feedback cue families: ${report.feedbackCueCount}\n\n## Runtime-enforced mix caps\n\n${table(['Family', 'Max concurrent voices'], Object.entries(report.mix.familyCaps).map(([family, cap]) => [family, cap]))}\n\n## Cue registry\n\n${table(['Cue', 'Family', 'Priority', 'Cooldown ms', 'Playback', 'Synth tones'], registryRows())}\n\n## Validation gaps\n\n${report.validation.gaps.length ? report.validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeHmhAudioSystemReport({ repoRoot = repoRootFromHere() } = {}) {
  const outputDir = path.join(repoRoot, 'docs', 'audio');
  mkdirSync(outputDir, { recursive: true });
  const report = buildHmhAudioSystemReport();
  const jsonPath = path.join(outputDir, 'hard-money-heroes-audio-system.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-audio-system.md');
  writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderHmhAudioSystemMarkdown(report), 'utf8');
  return Object.freeze({ report, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { report, jsonPath, mdPath } = writeHmhAudioSystemReport();
  console.log(`HMH audio system report written: ${jsonPath}`);
  console.log(`HMH audio markdown written: ${mdPath}`);
  console.log(`Status: ${report.validation.ok ? 'PASS' : 'FAIL'}; cues ${report.validation.cueCount}; sample cues ${report.manifestCueCount}`);
  if (!report.validation.ok) process.exitCode = 1;
}
