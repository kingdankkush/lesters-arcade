import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  LESTER_BLASTER_TACTICAL_CAMERA_MODEL,
  LESTER_BLASTER_TACTICAL_COMBAT_V2,
  LESTER_BLASTER_ENEMY_AI_STATE_MACHINE,
  LESTER_BLASTER_HUD_OVERLAY_MODEL,
} from '../apps/portal/src/arcade-core.mjs';
import { buildLevelOneBalanceTelemetrySnapshot } from '../apps/portal/src/hmh-level-one-balance-pass.mjs';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outputDir = join(repoRoot, 'docs', 'game-design');
mkdirSync(outputDir, { recursive: true });

const snapshot = Object.freeze({
  generatedBy: 'npm run design:balance',
  camera: LESTER_BLASTER_TACTICAL_CAMERA_MODEL,
  tacticalRoomTuning: LESTER_BLASTER_TACTICAL_COMBAT_V2.levelOne.tacticalRoomTuning,
  pacingRules: LESTER_BLASTER_TACTICAL_COMBAT_V2.pacingRules,
  enemyAiFairness: LESTER_BLASTER_ENEMY_AI_STATE_MACHINE.globalFairness,
  hudWidgets: LESTER_BLASTER_HUD_OVERLAY_MODEL.requiredWidgets,
  nextBalanceQuestions: Object.freeze([
    'Does rightward pressure advance the room quickly enough without feeling like auto-scroll?',
    'Can a new player identify safe crouch-cover positions before the first enemy shot?',
    'Are enemy tell frames visible for melee and ranged attacks before damage lands?',
    'Do explosive barrels solve crowd pressure without trivializing waves?',
    'Can the player exit back to Lester’s Arcade from pause or game-over without confusion?',
  ]),
});

const jsonPath = join(outputDir, 'hard-money-heroes-tactical-balance-snapshot.json');
const mdPath = join(outputDir, 'hard-money-heroes-tactical-balance-snapshot.md');

const room = snapshot.tacticalRoomTuning;
const markdown = `# Hard Money Heroes Tactical Balance Snapshot\n\nGenerated by \`npm run design:balance\`.\n\n## Camera model\n\n- Mode: ${snapshot.camera.mode}\n- Idle auto-scroll: ${snapshot.camera.autoScrollWhenIdle}\n- Player lead start: ${snapshot.camera.cameraLeadStartX}px\n- Backtrack floor: ${snapshot.camera.backtrackFloorScreenX}px\n- Engagement arena width: ${snapshot.camera.engagementArenaWidthPixels}px\n\n## Tactical room tuning\n\n- Player strafe lane: ${room.playerStrafeLanePixels}px\n- Minimum cover spacing: ${room.minCoverSpacingPixels}px\n- Enemy spawn delay: ${room.enemySpawnDelayFrames} frames\n- Ranged shot cooldown: ${room.rangedShotCooldownFrames} frames\n- Required cover kinds: ${room.requiredCoverKinds.join(', ')}\n\n## HUD widgets\n\n${snapshot.hudWidgets.map((widget) => `- ${widget}`).join('\n')}\n\n## Pacing rules\n\n${snapshot.pacingRules.map((rule) => `- ${rule}`).join('\n')}\n\n## Next balance questions\n\n${snapshot.nextBalanceQuestions.map((question) => `- ${question}`).join('\n')}\n`;

const levelOneSnapshot = buildLevelOneBalanceTelemetrySnapshot();
const levelOneJsonPath = join(outputDir, 'hard-money-heroes-level-1-balance-telemetry.json');
const levelOneMdPath = join(outputDir, 'hard-money-heroes-level-1-balance-telemetry.md');
const levelOneMarkdown = `# Hard Money Heroes Level 1 Balance Telemetry\n\nGenerated by \`npm run design:balance\`.\n\n## Six-area balance pass\n\n${levelOneSnapshot.areas.map((area) => `- ${area}`).join('\n')}\n\n## Timeline checkpoints\n\n| Time | Act | Spawn sec | Max enemies | Ranged | Drop chance |\n| --- | --- | ---: | ---: | ---: | ---: |\n${levelOneSnapshot.checkpoints.map((cp) => `| ${cp.seconds}s | ${cp.actId} | ${cp.director.spawnIntervalSeconds} | ${cp.director.maxEnemiesOnMap} | ${cp.composition.rangedEnemyShare} | ${cp.normalDropChance} |`).join('\n')}\n\n## XP / rewards\n\n- First upgrade expected: ${levelOneSnapshot.xpPacing.firstUpgradeExpectedSeconds}s\n- Swarm fighter kills by 8:00: ${levelOneSnapshot.killsModel.swarmFighter.killsAtEightMinutes}\n- Swarm fighter target level by 8:00: ${levelOneSnapshot.xpPacing.swarmFighter.targetLevelAtEightMinutes}\n- Normal drop chance: ${levelOneSnapshot.rewardModel.normalDropChanceAtStart} → ${levelOneSnapshot.rewardModel.normalDropChanceAtEightMinutes}\n\n## Boss choreography\n\n${levelOneSnapshot.bossChoreography.finalBoss.phases.map((phase) => `- ${phase.id}: ${phase.pattern} (${phase.telegraphFrames} tell frames)`).join('\n')}\n\n## Mechanic-changing upgrade cards\n\n${levelOneSnapshot.upgradeVariety.mechanicCards.map((card) => `- ${card.id}: ${card.mechanic}`).join('\n')}\n`;

writeFileSync(jsonPath, `${JSON.stringify(snapshot, null, 2)}\n`);
writeFileSync(mdPath, markdown);
writeFileSync(levelOneJsonPath, `${JSON.stringify(levelOneSnapshot, null, 2)}\n`);
writeFileSync(levelOneMdPath, levelOneMarkdown);

console.log(`Tactical balance snapshot written:`);
console.log(`- ${jsonPath}`);
console.log(`- ${mdPath}`);
console.log(`Level 1 balance telemetry written:`);
console.log(`- ${levelOneJsonPath}`);
console.log(`- ${levelOneMdPath}`);
