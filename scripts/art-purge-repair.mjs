import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { HMH_ANIMATED_ROSTER } from '../apps/portal/assets/generated/hmh-animated-roster/hmh-animated-roster.mjs';
import { buildArtPurgeRepairPlan } from '../apps/portal/src/hmh-art-repair.mjs';
import { buildGlobalArtCensus } from './global-art-census.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('\n', ' ').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function buildApprovedArtPurgeRepairPlan({ repoRoot = repoRootFromHere(), roster = HMH_ANIMATED_ROSTER } = {}) {
  const census = buildGlobalArtCensus({ repoRoot });
  const zeroAnimationActors = census.scorecard.categories.animationCoverage.gaps
    .filter((gap) => String(gap).includes(': zero-animation'))
    .map((gap) => String(gap).split(':')[0]);
  const repairPlan = buildArtPurgeRepairPlan({ roster, zeroAnimationActors });
  return Object.freeze({
    ...repairPlan,
    generatedBy: 'scripts/art-purge-repair.mjs',
    approvedCensus: Object.freeze({
      version: census.version,
      complianceScore: census.scorecard.overallScore,
      zeroAnimationActorCount: census.summary.runtimeZeroAnimationActorCount,
      source: 'docs/art/GLOBAL_ART_CENSUS.json',
    }),
  });
}

export function renderArtPurgeRepairMarkdown(plan) {
  const rows = plan.repairs.map((entry) => [
    entry.from,
    entry.action,
    entry.resolvedKey,
    entry.targetRenderable ? 'yes' : 'no',
    entry.reason,
  ]);
  const guardRows = plan.runtimeGuardrails.map((entry) => [entry.originalKey, entry.resolvedKey, entry.reason]);
  return `# Hard Money Heroes Art Purge + Auto-Repair Plan\n\nGenerated by \`${plan.generatedBy}\` from approved census \`${plan.approvedCensus.source}\`.\n\n## Summary\n\n- Plan version: ${plan.version}\n- Approved census version: ${plan.approvedCensus.version}\n- Approved census compliance score: ${plan.approvedCensus.complianceScore}/100\n- Inspected zero-animation actors: ${plan.summary.inspectedZeroAnimationActorCount}\n- Auto-repaired runtime actor keys: ${plan.summary.autoRepairCount}\n- Deferred/purge candidates: ${plan.summary.deferOrPurgeCount}\n- Unresolved: ${plan.summary.unresolvedCount}\n\n## Repair ledger\n\n${table(['From', 'Action', 'Resolved key', 'Target renderable', 'Reason'], rows)}\n\n## Runtime guardrails\n\nThese actor keys are automatically redirected so the live renderer never chooses an invisible zero-animation kit.\n\n${table(['Original key', 'Resolved key', 'Reason'], guardRows)}\n\n## Purge policy\n\n${plan.purgePolicy.map((item) => `- ${item}`).join('\n')}\n`;
}

export function writeArtPurgeRepairPlan({ repoRoot = repoRootFromHere() } = {}) {
  const plan = buildApprovedArtPurgeRepairPlan({ repoRoot });
  const outputDir = path.join(repoRoot, 'docs', 'art');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'ART_PURGE_REPAIR_PLAN.json');
  const mdPath = path.join(outputDir, 'ART_PURGE_REPAIR_PLAN.md');
  writeFileSync(jsonPath, `${JSON.stringify(plan, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderArtPurgeRepairMarkdown(plan), 'utf8');
  return Object.freeze({ plan, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { plan, jsonPath, mdPath } = writeArtPurgeRepairPlan();
  console.log(`Art purge/repair plan written: ${jsonPath}`);
  console.log(`Art purge/repair markdown written: ${mdPath}`);
  console.log(`Auto-repairs: ${plan.summary.autoRepairCount}; defer/purge: ${plan.summary.deferOrPurgeCount}; unresolved: ${plan.summary.unresolvedCount}`);
}
