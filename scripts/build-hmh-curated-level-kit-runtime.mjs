import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HMH_CURATED_LEVEL_KIT, curatedLevelKitAssetByKey } from '../apps/portal/assets/generated/hmh-curated-level-kit/hmh-curated-level-kit-manifest.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walkSourceFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkSourceFiles(full));
    else if (/\.(mjs|js)$/.test(entry.name)) out.push(full);
  }
  return out;
}

const sourceFiles = [
  path.join(repoRoot, 'apps/portal/main.js'),
  ...walkSourceFiles(path.join(repoRoot, 'apps/portal/src')),
];
const relativeSourceFiles = sourceFiles.map((file) => path.relative(repoRoot, file).replaceAll('\\', '/'));
const keyPattern = /['"]((?:level-1|curated-ground|curated-prop|universal)\/[^'"]+)['"]/g;
const keys = new Set();
for (const file of sourceFiles) {
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(keyPattern)) keys.add(match[1]);
}
const assets = [...keys]
  .map((key) => curatedLevelKitAssetByKey(key))
  .filter(Boolean)
  .sort((a, b) => a.key.localeCompare(b.key));
const missing = [...keys].filter((key) => !curatedLevelKitAssetByKey(key)).sort();
const out = {
  id: HMH_CURATED_LEVEL_KIT.id,
  runtimeFlavor: 'runtime-slim',
  sourcePolicy: HMH_CURATED_LEVEL_KIT.sourcePolicy,
  sourceRoot: HMH_CURATED_LEVEL_KIT.sourceRoot,
  generatedRoot: HMH_CURATED_LEVEL_KIT.generatedRoot,
  generatedFrom: 'scripts/build-hmh-curated-level-kit-runtime.mjs',
  sourceFiles: relativeSourceFiles,
  totalReferencedKeys: keys.size,
  missing,
  assets,
};
const moduleText = `// Generated by scripts/build-hmh-curated-level-kit-runtime.mjs.\n// Slim exact-key runtime index; raw source masters are archived in the external vault.\n\nexport const HMH_CURATED_LEVEL_KIT = Object.freeze(${JSON.stringify(out, null, 2)});\n\nconst CURATED_LEVEL_KIT_ASSET_BY_KEY = new Map(HMH_CURATED_LEVEL_KIT.assets.map((asset) => [asset.key, Object.freeze(asset)]));\n\nexport function curatedLevelKitAssetByKey(key) {\n  return CURATED_LEVEL_KIT_ASSET_BY_KEY.get(key) ?? null;\n}\n`;
const outPath = path.join(repoRoot, 'apps/portal/assets/generated/hmh-curated-level-kit/hmh-curated-level-kit-runtime.mjs');
writeFileSync(outPath, moduleText, 'utf8');
console.log(JSON.stringify({ outPath, referencedKeys: keys.size, assets: assets.length, missing }, null, 2));
