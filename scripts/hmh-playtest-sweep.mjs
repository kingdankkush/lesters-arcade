import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { HMH_PLAYTEST_SCENARIOS, buildStructuredPlaytestSweep, validateStructuredPlaytestSweep } from '../apps/portal/src/hmh-playtest-sweep.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function renderStructuredPlaytestSweepMarkdown(sweep = buildStructuredPlaytestSweep()) {
  const validation = validateStructuredPlaytestSweep(sweep);
  const scenarioRows = HMH_PLAYTEST_SCENARIOS.map((scenario) => [
    scenario.priority,
    scenario.id,
    scenario.title,
    scenario.steps.join(' → '),
    scenario.expected.join('; '),
    scenario.automatedEvidence.join(', '),
  ]);
  const bugRows = sweep.bugAreas.map((area) => [area.severity, area.id, area.guard, area.status]);
  return `# Hard Money Heroes Structured Playtest and Bug Sweep\n\nGenerated by \`scripts/hmh-playtest-sweep.mjs\`.\n\n## Summary\n\n- Version: ${sweep.version}\n- Status: ${validation.ok ? 'PASS' : 'FAIL'}\n- Scenarios: ${sweep.summary.scenarioCount}\n- P0 scenarios: ${sweep.summary.p0ScenarioCount}\n- Bug areas: ${sweep.summary.bugAreaCount}\n- Uncovered bug areas: ${sweep.summary.uncoveredBugAreaCount}\n\n## Playtest script\n\n${table(['Priority', 'ID', 'Title', 'Steps', 'Expected', 'Automated evidence'], scenarioRows)}\n\n## Bug sweep\n\n${table(['Severity', 'Area', 'Guard', 'Status'], bugRows)}\n\n## Gaps\n\n${validation.gaps.length ? validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeStructuredPlaytestSweep({ repoRoot = repoRootFromHere() } = {}) {
  const sweep = buildStructuredPlaytestSweep();
  const validation = validateStructuredPlaytestSweep(sweep);
  const outputDir = path.join(repoRoot, 'docs', 'qa');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'hard-money-heroes-playtest-sweep.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-playtest-sweep.md');
  writeFileSync(jsonPath, `${JSON.stringify({ sweep, validation }, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderStructuredPlaytestSweepMarkdown(sweep), 'utf8');
  return Object.freeze({ sweep, validation, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { sweep, validation, jsonPath, mdPath } = writeStructuredPlaytestSweep();
  console.log(`HMH playtest sweep written: ${jsonPath}`);
  console.log(`HMH playtest markdown written: ${mdPath}`);
  console.log(`Status: ${validation.ok ? 'PASS' : 'FAIL'}; scenarios ${sweep.summary.scenarioCount}; bug areas ${sweep.summary.bugAreaCount}`);
  if (!validation.ok) process.exitCode = 1;
}
