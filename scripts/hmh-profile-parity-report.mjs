import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { createInitialArcadeState, createPlayerProfile } from '../apps/portal/src/arcade-core.mjs';
import { buildProfilePersistenceParityReport, validateProfilePersistenceParity } from '../apps/portal/src/hmh-profile-parity.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function buildProfileParityCertification() {
  const wallet = '0x0000000000000000000000000000000000000035';
  const state = createInitialArcadeState();
  state.profiles[wallet] = createPlayerProfile(wallet, {
    avatarDataUrl: 'data:image/jpeg;base64,wo35-local-avatar-fixture',
    avatarUri: 'ipfs://wo35-chain-avatar-fixture',
  });
  state.profiles[wallet].handle = 'WO35Tester';
  state.profiles[wallet].usernameSet = true;
  state.profiles[wallet].preferences.selectedCharacterId = 'lit-valkyrie';
  const report = buildProfilePersistenceParityReport({
    state,
    wallet,
    chainProfile: { displayName: 'WO35Chain', avatarUri: 'ipfs://wo35-chain-avatar-fixture' },
  });
  const validation = validateProfilePersistenceParity(report);
  return Object.freeze({ version: 'wo-35-profile-parity-cert-v1', report, validation });
}

export function renderProfileParityMarkdown(cert = buildProfileParityCertification()) {
  const rows = [
    ['Wallet', cert.report.identity.wallet],
    ['Display name source', cert.report.identity.source.displayName],
    ['Avatar source', cert.report.identity.source.avatar],
    ['Selected character source', cert.report.identity.source.selectedCharacter],
    ['Avatar parity', cert.report.summary.avatarParity],
    ['Selected character parity', cert.report.summary.selectedCharacterParity],
  ];
  return `# Hard Money Heroes Profile Persistence Parity\n\nGenerated by \`scripts/hmh-profile-parity-report.mjs\`.\n\n## Summary\n\n- Version: ${cert.version}\n- Status: ${cert.validation.ok ? 'PASS' : 'FAIL'}\n- Local profile present: ${cert.report.summary.localProfilePresent}\n- Chain profile present: ${cert.report.summary.chainProfilePresent}\n\n${table(['Check', 'Value'], rows)}\n\n## Gaps\n\n${cert.validation.gaps.length ? cert.validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeProfileParityCertification({ repoRoot = repoRootFromHere() } = {}) {
  const cert = buildProfileParityCertification();
  const outputDir = path.join(repoRoot, 'docs', 'qa');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'hard-money-heroes-profile-parity.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-profile-parity.md');
  writeFileSync(jsonPath, `${JSON.stringify(cert, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderProfileParityMarkdown(cert), 'utf8');
  return Object.freeze({ cert, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { cert, jsonPath, mdPath } = writeProfileParityCertification();
  console.log(`HMH profile parity report written: ${jsonPath}`);
  console.log(`HMH profile parity markdown written: ${mdPath}`);
  console.log(`Status: ${cert.validation.ok ? 'PASS' : 'FAIL'}; wallet ${cert.report.identity.wallet}`);
  if (!cert.validation.ok) process.exitCode = 1;
}
