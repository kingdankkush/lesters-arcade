import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildBossBalanceCards, buildBossBalanceScorecard } from '../apps/portal/src/hmh-boss-balance-pass.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function renderBossBalanceMarkdown(scorecard) {
  const rows = scorecard.cards.map((card) => [
    card.role,
    card.enemyId,
    card.title,
    card.firstSeenSeconds,
    card.phaseCount,
    card.role === 'boss' ? card.fanShotsByPhase.join('/') : `enrage ${card.enrageHpPct}%`,
  ]);
  return `# Hard Money Heroes Boss Balance Pass\n\nGenerated by \`scripts/boss-balance-pass.mjs\`.\n\n## Summary\n\n- Version: ${scorecard.version}\n- Score: ${scorecard.overallScore}/100\n- Boss cards: ${scorecard.summary.cardCount}\n- Mini-bosses: ${scorecard.summary.miniBossCount}\n- Major bosses: ${scorecard.summary.majorBossCount}\n- First mini-boss beat: ${scorecard.summary.firstMiniBossSeconds}s\n- First major boss beat: ${scorecard.summary.firstMajorBossSeconds}s\n- Minimum schedule gap: ${scorecard.summary.minScheduleGapSeconds}s\n- Status: ${scorecard.validation.ok ? 'PASS' : 'FAIL'}\n\n## Cards\n\n${table(['Role', 'Enemy ID', 'Title', 'First seen', 'Phases', 'Balance read'], rows)}\n\n## Gaps\n\n${scorecard.validation.gaps.length ? scorecard.validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeBossBalancePass({ repoRoot = repoRootFromHere() } = {}) {
  const cards = buildBossBalanceCards();
  const scorecard = buildBossBalanceScorecard(cards);
  const outputDir = path.join(repoRoot, 'docs', 'game-design');
  mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'hard-money-heroes-boss-balance-pass.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-boss-balance-pass.md');
  writeFileSync(jsonPath, `${JSON.stringify(scorecard, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderBossBalanceMarkdown(scorecard), 'utf8');
  return Object.freeze({ scorecard, jsonPath, mdPath });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { scorecard, jsonPath, mdPath } = writeBossBalancePass();
  console.log(`Boss balance pass written: ${jsonPath}`);
  console.log(`Boss balance markdown written: ${mdPath}`);
  console.log(`Status: ${scorecard.validation.ok ? 'PASS' : 'FAIL'}; score ${scorecard.overallScore}/100; cards ${scorecard.summary.cardCount}`);
  if (!scorecard.validation.ok) process.exitCode = 1;
}
