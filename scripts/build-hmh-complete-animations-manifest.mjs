#!/usr/bin/env node
// Build a runtime manifest from harvested hmh-complete-animations frames.
//
// Scans apps/portal/assets/generated/hmh-complete-animations/{heroes,enemies}/
// folders named <character>-<state>-<direction>/frame-N.png and emits
// hmh-complete-animations.mjs shaped like the animated roster:
//   { <char>: { role, animations: { <state>: { <dir>: [paths...] } } } }
//
// COMPLETENESS GATE: a character only ENTERS the manifest's `ready` map when
// it has every REQUIRED state present (any direction). Partial kits stay in
// `partial` so the runtime never mixes the new design with old-roster states
// (one design per character — mixing is what caused the hero flicker bug).
//
// Usage: node scripts/build-hmh-complete-animations-manifest.mjs
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = path.join(ROOT, 'apps/portal/assets/generated/hmh-complete-animations');
const OUT = path.join(BASE, 'hmh-complete-animations.mjs');

const DIRECTIONS = ['east', 'north-east', 'north', 'north-west', 'west', 'south-west', 'south', 'south-east'];
// Required states for a kit to be considered complete enough to swap designs.
// Heroes need locomotion + combat + reaction; enemies need walk-substitutes
// (attack-tell doubles as "alert"), hit and death.
const REQUIRED = {
  heroes: ['idle', 'walk', 'shoot', 'hurt', 'death'],
  enemies: ['idle', 'walk', 'attack-tell', 'hit', 'death'],
};
const ROLE = { heroes: 'hero', enemies: 'enemy' };

function parseDirName(name) {
  // <character>-<state>-<direction> where state/character contain hyphens.
  for (const dir of [...DIRECTIONS].sort((a, b) => b.length - a.length)) {
    if (name.endsWith('-' + dir)) {
      const rest = name.slice(0, -(dir.length + 1));
      return { rest, dir };
    }
  }
  return null;
}

const KNOWN_STATES = ['idle', 'walk', 'run', 'crouch', 'fall', 'shoot', 'melee', 'throw', 'hurt', 'death', 'victory',
  'attack-tell', 'melee-counter', 'hit', 'optional-gore-overlay'];

function splitCharState(rest) {
  for (const st of [...KNOWN_STATES].sort((a, b) => b.length - a.length)) {
    if (rest.endsWith('-' + st)) return { char: rest.slice(0, -(st.length + 1)), state: st };
  }
  return null;
}

const manifest = {};
for (const set of ['heroes', 'enemies']) {
  const setDir = path.join(BASE, set);
  if (!existsSync(setDir)) continue;
  for (const entry of readdirSync(setDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const parsedDir = parseDirName(entry.name);
    if (!parsedDir) continue;
    const cs = splitCharState(parsedDir.rest);
    if (!cs) continue;
    const frames = readdirSync(path.join(setDir, entry.name))
      .filter((f) => /^frame-\d+\.png$/.test(f))
      .sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10))
      .map((f) => `./assets/generated/hmh-complete-animations/${set}/${entry.name}/${f}`);
    if (!frames.length) continue;
    manifest[cs.char] ??= { role: ROLE[set], set, animations: {} };
    manifest[cs.char].animations[cs.state] ??= {};
    manifest[cs.char].animations[cs.state][parsedDir.dir] = frames;
  }
}

// Completeness report + gate
const ready = {};
const partial = {};
for (const [char, data] of Object.entries(manifest)) {
  const required = REQUIRED[data.set] ?? [];
  const have = Object.keys(data.animations);
  const missing = required.filter((s) => !have.includes(s));
  const dirCount = Object.fromEntries(have.map((s) => [s, Object.keys(data.animations[s]).length]));
  if (missing.length === 0) {
    ready[char] = data;
  } else {
    partial[char] = { missing, states: dirCount };
  }
  console.log(`${char} (${data.set}): states=${JSON.stringify(dirCount)} missing=${JSON.stringify(missing)} -> ${missing.length === 0 ? 'READY' : 'partial'}`);
}

const body = `// AUTO-GENERATED by scripts/build-hmh-complete-animations-manifest.mjs. Do not hand-edit.
// New-design animation kits harvested from PixelLab (hmh-complete-animations).
// READY = has all required states (${JSON.stringify(REQUIRED)}); only READY
// characters may be wired into the runtime roster — partial kits would mix
// designs per-state (the hero-flicker bug).
export const HMH_COMPLETE_ANIMATIONS_READY = Object.freeze(${JSON.stringify(ready, null, 1)});
export const HMH_COMPLETE_ANIMATIONS_PARTIAL = Object.freeze(${JSON.stringify(partial, null, 1)});
`;
writeFileSync(OUT, body);
console.log(`\nWrote ${OUT}`);
console.log(`READY: ${Object.keys(ready).join(', ') || '(none)'}`);
console.log(`PARTIAL: ${Object.keys(partial).join(', ') || '(none)'}`);
