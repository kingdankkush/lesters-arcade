import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { HMH_COPY_SHEET, collectHmhCopyTexts, validateHmhCopySheet } from '../apps/portal/src/hmh-copy-sheet.mjs';

function repoRootFromHere() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

export function renderHmhCopySheetMarkdown(sheet = HMH_COPY_SHEET) {
  const validation = validateHmhCopySheet(sheet);
  const surfaceRows = sheet.surfaces.map((surface) => [surface.id, surface.surface, surface.file, surface.text]);
  const glossaryRows = sheet.glossary.map((entry) => [entry.term, entry.approved]);
  return `# Hard Money Heroes Copy Sheet\n\nGenerated by \`scripts/hmh-copy-sheet.mjs\`.\n\n## Summary\n\n- Version: ${sheet.version}\n- Status: ${validation.ok ? 'PASS' : 'FAIL'}\n- Text entries: ${validation.textCount}\n- Runtime surfaces: ${validation.surfaceCount}\n\n## Voice\n\n${sheet.voice.pillars.map((pillar) => `- ${pillar}`).join('\n')}\n\n## Avoid\n\n${sheet.voice.avoid.map((item) => `- ${item}`).join('\n')}\n\n## Runtime surfaces\n\n${table(['ID', 'Surface', 'File', 'Approved copy'], surfaceRows)}\n\n## Mode select\n\n- **${sheet.modeSelect.free.label}:** ${sheet.modeSelect.free.copy}\n- **${sheet.modeSelect.ranked.label}:** ${sheet.modeSelect.ranked.copy}\n\n## Level intro\n\n- **Title:** ${sheet.levelIntro.title}\n- **Controls:** ${sheet.levelIntro.controlsSummary}\n- **Goal:** ${sheet.levelIntro.goalCopy}\n\n## Glossary\n\n${table(['Term', 'Approved use'], glossaryRows)}\n\n## Validation gaps\n\n${validation.gaps.length ? validation.gaps.map((gap) => `- ${gap}`).join('\n') : '- None'}\n`;
}

export function writeHmhCopySheet({ repoRoot = repoRootFromHere() } = {}) {
  const outputDir = path.join(repoRoot, 'docs', 'copy');
  mkdirSync(outputDir, { recursive: true });
  const validation = validateHmhCopySheet(HMH_COPY_SHEET);
  const payload = Object.freeze({
    sheet: HMH_COPY_SHEET,
    validation,
    texts: collectHmhCopyTexts(HMH_COPY_SHEET),
  });
  const jsonPath = path.join(outputDir, 'hard-money-heroes-copy-sheet.json');
  const mdPath = path.join(outputDir, 'hard-money-heroes-copy-sheet.md');
  writeFileSync(jsonPath, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  writeFileSync(mdPath, renderHmhCopySheetMarkdown(HMH_COPY_SHEET), 'utf8');
  return Object.freeze({ jsonPath, mdPath, validation });
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const { jsonPath, mdPath, validation } = writeHmhCopySheet();
  console.log(`HMH copy sheet written: ${jsonPath}`);
  console.log(`HMH copy markdown written: ${mdPath}`);
  console.log(`Status: ${validation.ok ? 'PASS' : 'FAIL'}; texts ${validation.textCount}; surfaces ${validation.surfaceCount}`);
  if (!validation.ok) process.exitCode = 1;
}
