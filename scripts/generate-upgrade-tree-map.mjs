import { writeFile } from 'node:fs/promises';

import {
  LESTER_BLASTER_ROGUELIKE_SKILL_LIBRARY,
  LESTER_BLASTER_ISOMETRIC_ROGUELIKE,
} from '../apps/portal/src/arcade-core.mjs';

const outPath = new URL('../docs/game-design/UPGRADE_TREE_MAP.md', import.meta.url);

function safeNodeId(id) {
  return `skill_${String(id).replace(/[^a-zA-Z0-9_]/g, '_')}`;
}

function gateLabel(skill) {
  const gate = skill.gate ?? {};
  const parts = [];
  if (gate.playerLevel) parts.push(`level ${gate.playerLevel}+`);
  for (const req of gate.requires ?? []) parts.push(`${req.skillId} r${req.rank}`);
  return parts.length ? parts.join(', ') : 'start-anytime';
}

function kindLabel(skill) {
  if (skill.kind === 'evolution') return 'golden evolution';
  if (skill.kind === 'unlock') return 'unlock stem';
  if (skill.gate?.requires?.length) return 'dependent stem';
  if (skill.gate?.playerLevel) return 'level-gated base';
  return 'universal base';
}

function render() {
  const skills = [...LESTER_BLASTER_ROGUELIKE_SKILL_LIBRARY];
  const lines = [
    '# Upgrade Tree Map',
    '',
    '<!-- Generated by scripts/generate-upgrade-tree-map.mjs. Do not hand-edit. -->',
    '',
    `- Draft card count: ${LESTER_BLASTER_ISOMETRIC_ROGUELIKE.levelUp.choicesPerLevel}`,
    `- Rerolls per level: ${LESTER_BLASTER_ISOMETRIC_ROGUELIKE.levelUp.rerollsPerLevel}`,
    '- Slot A: continuation, newly unlocked dependent stem, or owned-tree rank-up.',
    '- Slot B: fresh new tree, falling back to a second continuation only when no new tree remains.',
    '',
    '```mermaid',
    'flowchart LR',
  ];

  for (const skill of skills) {
    const id = safeNodeId(skill.id);
    const title = String(skill.title).replace(/"/g, "'");
    const label = `${title}<br/>${kindLabel(skill)}<br/>max r${skill.maxRank}`;
    lines.push(`  ${id}["${label}"]`);
  }
  for (const skill of skills) {
    for (const req of skill.gate?.requires ?? []) {
      lines.push(`  ${safeNodeId(req.skillId)} -- "r${req.rank}" --> ${safeNodeId(skill.id)}`);
    }
  }
  for (const skill of skills.filter((skill) => skill.gate?.playerLevel && !(skill.gate?.requires?.length))) {
    lines.push(`  level_${skill.gate.playerLevel}((Level ${skill.gate.playerLevel}+)) --> ${safeNodeId(skill.id)}`);
  }
  lines.push('```', '', '## Review Table', '', '| Skill | Kind | Gate | Max Rank | Category |', '|---|---:|---|---:|---|');
  for (const skill of skills) {
    lines.push(`| ${skill.title} \`${skill.id}\` | ${kindLabel(skill)} | ${gateLabel(skill)} | ${skill.maxRank} | ${skill.category} |`);
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
}

await writeFile(outPath, render());
console.log(new URL(outPath).pathname);
